// resolvconfBackend writes /etc/resolv.conf with the VPN-provided DNS servers
// and tries to make it immutable so NetworkManager / dhclient cannot overwrite
// it. If chattr +i fails (no CAP_LINUX_IMMUTABLE, AppArmor block, or
// /etc unsupported FS) a fallback watcher rewrites the file periodically.
type resolvconfBackend struct {
	mu          sync.Mutex
	applied     bool
	backup      []byte
	content     string
	watchCancel context.CancelFunc
}

const resolvconfMarker = "# Generated by MidoriVPN while protected mode is active."

func backupPath() (string, error) {
	stateHome := strings.TrimSpace(os.Getenv("XDG_STATE_HOME"))
	if stateHome == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", err
		}
		stateHome = filepath.Join(home, ".local", "state")
	}
	dir := filepath.Join(stateHome, "midorivpn")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	return filepath.Join(dir, "resolv.conf.backup"), nil
}

func persistBackup(data []byte) error {
	path, err := backupPath()
	if err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".resolv-backup-*")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer os.Remove(tmpPath) //nolint:errcheck
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpPath, path)
}

// RecoverStaleResolvconf restores DNS after an unclean prior exit. Kernel
// routes and nftables state disappear on reboot, while /etc/resolv.conf may
// survive; therefore its original content is persisted before every mutation.
func RecoverStaleResolvconf() error {
	path, err := backupPath()
	if err != nil {
		return err
	}
	backup, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	current, err := os.ReadFile("/etc/resolv.conf")
	if err != nil {
		return err
	}
	if !strings.Contains(string(current), resolvconfMarker) {
		return os.Remove(path)
	}
	_ = runChattr("-i", "/etc/resolv.conf")
	if err := os.WriteFile("/etc/resolv.conf", backup, 0o644); err != nil {
		return fmt.Errorf("restore stale resolv.conf: %w", err)
	}
	return os.Remove(path)
}

func newResolvconfBackend() *resolvconfBackend { return &resolvconfBackend{} }

func (b *resolvconfBackend) Kind() Kind { return KindResolvconf }

func (b *resolvconfBackend) Apply(iface string, servers []string) error {
	_ = iface // unused; kept for interface symmetry

	b.mu.Lock()
	defer b.mu.Unlock()

	slog.Info("dns: protecting via resolvconf", "servers", logredact.IPs(servers))

	if b.backup == nil {
		data, err := os.ReadFile("/etc/resolv.conf")
		if err != nil {
			return fmt.Errorf("backup resolv.conf: %w", err)
		}
		b.backup = append([]byte(nil), data...)
	}

	var sb strings.Builder
	sb.WriteString(resolvconfMarker + "\n")
	for _, server := range servers {
		server = strings.TrimSpace(server)
		if server == "" {
			continue
		}
		if net.ParseIP(server) == nil {
			return fmt.Errorf("invalid DNS server %q", server)
		}
		sb.WriteString("nameserver ")
		sb.WriteString(server)
		sb.WriteByte('\n')
	}
	content := sb.String()
	slog.Debug("dns: new resolv.conf content", "content", logredact.Generic(content))
	if err := persistBackup(b.backup); err != nil {
		return fmt.Errorf("persist resolv.conf backup: %w", err)
	}

	// If NetworkManager manages resolv.conf via a symlink to its own file,
	// write through to the real target first.
	if target, err := os.Readlink("/etc/resolv.conf"); err == nil {
		slog.Info("dns: writing to symlink target", "target", target)
		_ = os.WriteFile(target, []byte(content), 0o644)
	}
	if err := os.WriteFile("/etc/resolv.conf", []byte(content), 0o644); err != nil {
		return fmt.Errorf("write resolv.conf: %w", err)
	}
	slog.Info("dns: wrote resolv.conf successfully")

	// Try to make the file immutable (requires CAP_LINUX_IMMUTABLE).
	// On failure spawn a watcher goroutine that rewrites the file if it
	// gets overwritten by NetworkManager / resolvconf.
	if err := runChattr("+i", "/etc/resolv.conf"); err != nil {
		ctx, cancel := context.WithCancel(context.Background())
		b.watchCancel = cancel
		dnsContent := content
		go func() {
			ticker := time.NewTicker(2 * time.Second)
			defer ticker.Stop()
			for {
				select {
				case <-ctx.Done():
					return
				case <-ticker.C:
					cur, err := os.ReadFile("/etc/resolv.conf")
					if err != nil || string(cur) != dnsContent {
						_ = os.WriteFile("/etc/resolv.conf", []byte(dnsContent), 0o644)
					}
				}
			}
		}()
	}

	b.content = content
	b.applied = true
	return nil
}

func (b *resolvconfBackend) Restore() error {
	b.mu.Lock()
	defer b.mu.Unlock()

	if b.watchCancel != nil {
		b.watchCancel()
		b.watchCancel = nil
	}
	if !b.applied {
		return nil
	}
	// Remove the immutable flag (best-effort; only meaningful if chattr +i
	// previously succeeded).
	_ = runChattr("-i", "/etc/resolv.conf")
	if b.backup != nil {
		if err := os.WriteFile("/etc/resolv.conf", b.backup, 0o644); err != nil {
			slog.Warn("dns: failed to restore resolv.conf", "err", err)
		}
	}
	b.applied = false
	b.backup = nil
	b.content = ""
	if path, err := backupPath(); err == nil {
		_ = os.Remove(path)
	}
	return nil
}

func runChattr(arguments ...string) error {
	path, err := exec.LookPath("chattr")
	if err != nil {
		return err
	}
	var header unix.CapUserHeader
	header.Version = unix.LINUX_CAPABILITY_VERSION_3
	var data [2]unix.CapUserData
	if err := unix.Capget(&header, &data[0]); err != nil {
		return err
	}
	data[0].Inheritable |= 1<<unix.CAP_DAC_OVERRIDE | 1<<unix.CAP_LINUX_IMMUTABLE
	if err := unix.Capset(&header, &data[0]); err != nil {
		return err
	}
	command := exec.Command(path, arguments...)
	command.SysProcAttr = &syscall.SysProcAttr{AmbientCaps: []uintptr{unix.CAP_DAC_OVERRIDE, unix.CAP_LINUX_IMMUTABLE}}
	return command.Run()
}
