//go:build linux

package dns

import (
	"fmt"
	"os"
	"strings"
)

// Direct resolver writes are deliberately unavailable. Network capabilities
// must not be extended with filesystem override/immutable privileges to make
// this backend work. A separate, narrowly authorized DNS backend is required
// before supporting hosts not managed by systemd-resolved.
type resolvconfBackend struct{}

const resolvconfMarker = "# Generated by MidoriVPN while protected mode is active."

func newResolvconfBackend() *resolvconfBackend { return &resolvconfBackend{} }
func (b *resolvconfBackend) Kind() Kind        { return KindResolvconf }
func (b *resolvconfBackend) Apply(string, []string) error {
	return fmt.Errorf("DNS protection requires systemd-resolved managing /etc/resolv.conf; direct resolver writes are disabled")
}
func (b *resolvconfBackend) Restore() error { return nil }

// A prior privileged release may have left a protected resolver behind. Never
// restore system configuration from a caller-controlled backup. Report it for
// administrator recovery; do not remove the backup or alter immutable flags.
func RecoverStaleResolvconf() error {
	current, err := os.ReadFile("/etc/resolv.conf")
	if err != nil {
		return err
	}
	if strings.Contains(string(current), resolvconfMarker) {
		return fmt.Errorf("legacy MidoriVPN resolver state requires administrator recovery before connecting")
	}
	return nil
}
